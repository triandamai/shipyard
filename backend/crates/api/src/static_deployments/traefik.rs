use std::fmt::Write as _;
use uuid::Uuid;

use crate::resources::{hostname_to_router_name, is_convenience_domain};

/// Writes a Traefik dynamic configuration file for a static project's custom domains.
/// Routes each domain directly to the shipyard-backend (port 3001), serving the project's
/// alias or deployment with automatic Let's Encrypt TLS.
pub async fn sync_static_project_traefik_config(
    db: &sqlx::PgPool,
    project_id: Uuid,
    dynamic_config_dir: Option<&str>,
    entrypoint_http: &str,
    entrypoint_https: &str,
) {
    let Some(dir) = dynamic_config_dir else { return };

    let file_stem = format!("static-project-{project_id}");
    let path = std::path::Path::new(dir).join(format!("{file_stem}.yml"));

    // Fetch all custom domains for this static project
    let rows: Vec<(String, String, bool, String)> = match sqlx::query_as(
        "SELECT hostname, alias, tls_enabled, cert_provider
         FROM static_project_domains WHERE project_id = $1 ORDER BY created_at ASC",
    )
    .bind(project_id)
    .fetch_all(db)
    .await
    {
        Ok(r) => r,
        Err(e) => {
            tracing::warn!("sync_static_project_traefik_config: DB error: {e}");
            return;
        }
    };

    if rows.is_empty() {
        let _ = tokio::fs::remove_file(&path).await;
        tracing::info!("Removed Traefik dynamic config for static project {project_id}: {path:?}");
        return;
    }

    let mut out = String::from("# Auto-generated by Shipyard for Static Project — do not edit manually\n");
    out.push_str("http:\n");
    out.push_str("  routers:\n");

    for (hostname, _alias, tls_enabled, cert_provider) in &rows {
        let rn = hostname_to_router_name(hostname);
        let convenience = is_convenience_domain(hostname);
        let prefix_mw = format!("{rn}-static-prefix");

        // HTTP router
        let _ = write!(out, "    {rn}-http:\n");
        let _ = write!(out, "      rule: \"Host(`{hostname}`)\"\n");
        let _ = write!(out, "      entryPoints:\n");
        let _ = write!(out, "        - {entrypoint_http}\n");
        let _ = write!(out, "      middlewares:\n");
        let _ = write!(out, "        - {prefix_mw}\n");
        let _ = write!(out, "      service: shipyard-backend\n");

        // HTTPS router
        let _ = write!(out, "    {rn}-https:\n");
        let _ = write!(out, "      rule: \"Host(`{hostname}`)\"\n");
        let _ = write!(out, "      entryPoints:\n");
        let _ = write!(out, "        - {entrypoint_https}\n");
        let _ = write!(out, "      middlewares:\n");
        let _ = write!(out, "        - {prefix_mw}\n");
        if convenience || !*tls_enabled {
            let _ = write!(out, "      tls: {{}}\n");
        } else {
            let _ = write!(out, "      tls:\n");
            let _ = write!(out, "        certResolver: {cert_provider}\n");
        }
        let _ = write!(out, "      service: shipyard-backend\n");
    }

    out.push_str("  middlewares:\n");
    for (hostname, alias, _, _) in &rows {
        let rn = hostname_to_router_name(hostname);
        let prefix_mw = format!("{rn}-static-prefix");
        let _ = write!(out, "    {prefix_mw}:\n");
        let _ = write!(out, "      addPrefix:\n");
        let _ = write!(out, "        prefix: \"/alias/{project_id}/{alias}\"\n");
    }

    if let Err(e) = tokio::fs::create_dir_all(dir).await {
        tracing::warn!("sync_static_project_traefik_config: could not create dir '{dir}': {e}");
        return;
    }
    if let Err(e) = tokio::fs::write(&path, out.as_bytes()).await {
        tracing::warn!("sync_static_project_traefik_config: could not write '{path:?}': {e}");
    } else {
        tracing::info!("Wrote Traefik dynamic config for static project {project_id}: {path:?}");
    }
}
